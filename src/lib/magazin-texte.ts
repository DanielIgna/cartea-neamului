/** Toate textele unei categorii noi, pe limbi (pentru teste și amprenta SEO). */
export const CATEGORY_TEXT = { accesorii: ACCESORII, jurnal: JURNALE, generic: GENERIC, set: SET } as const;

export type CategoryText = ShopText & Omit<Cat, keyof ShopText> & SetTexts;

const key = (l: Locale): TextLocale => (l === "en-US" ? "en-GB" : l);

/**
 * Textele unei categorii în limba dată: cele ale invitațiilor, peste care vin cele ale categoriei. Pentru invitații, exact
 * textele de până acum (plus blocul „Completează setul”).
 */
export function categoryText(category: "invitatie" | "accesorii" | "jurnal", locale: Locale): CategoryText {
  const k = key(locale);
  const base = SHOP_TEXT[k] ?? SHOP_TEXT["en-GB"];
  const set = SET[k] ?? SET["en-GB"];
  if (category === "invitatie") return { ...base, ...set, partsLabel: "", parts: {}, prodTitle: "", prodText: "" };
  const cat = (category === "accesorii" ? ACCESORII : JURNALE);
  return { ...base, ...(GENERIC[k] ?? GENERIC["en-GB"]), ...(cat[k] ?? cat["en-GB"]), ...set };
}
